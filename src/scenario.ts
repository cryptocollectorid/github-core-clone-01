export interface ScenarioUser {
  id: number;
  login: string;
  email: string;
}

function generateUsers(rng: ScenarioRng, count: number): ScenarioUser[] {
  const used = new Set<string>();
  const users: ScenarioUser[] = [];
  for (let i = 0; i < count; i += 1) {
    const first = rng.pick(FIRST_NAMES);
    const last = rng.pick(LAST_NAMES);
    const base = `${first}${last}`;
    let login = base;
    let suffix = 2;
    while (used.has(login)) {
      login = `${base}-${suffix}`;
      suffix += 1;
    }
    used.add(login);
    users.push({ id: 1000 + i, login, email: `${login}@example.invalid` });
  }
  return users;
}

/** The viewer login for this instance, derived from the fixed scenario seed. */
export function deriveViewerLogin(): string {
  try {
    const users = generateUsers(new ScenarioRng(scenarioSeedFor('users')), 12);
    if (users.length > 0 && users[0].login) return users[0].login;
  } catch {
    // fall through to the fallback below
  }
  return 'adaiversen';
}

